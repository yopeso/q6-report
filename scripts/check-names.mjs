// pnpm check:names holds every file of the repository to naming nothing but itself: no project or team that tried it,
// no other report and no code of the suite it came from. The names that must not appear are private, so they come in
// through Q6_REPORT_PRIVATE_NAMES, a pattern kept as a secret, and only the rules that name nothing are written here.
import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';

// The word q6 stands only in the package's own name and in the footer the page carries.
const ALLOWED_Q6 = /q6-report|Generated by q6/gi;
const RULES = [
  { name: 'the word q6 outside the name q6-report', pattern: /\bq6\b/i, allowed: ALLOWED_Q6 },
  { name: 'another report', pattern: /allure/i },
  { name: 'code of the suite it came from', pattern: /@q6\/|packages\/framework|q6Look/ },
];
// Fonts, images and archives hold no words to check.
const BINARY = /\.(png|jpe?g|gif|webp|ico|woff2?|jar|zip|gz)$/i;
// This file spells out the words it looks for, so it is the one file not held to them.
const ITSELF = 'scripts/check-names.mjs';

function filesOfTheRepository() {
  const listed = spawnSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '-z'], { encoding: 'utf8' });
  if (listed.status !== 0) throw new Error(`git could not list the repository's files: ${listed.stderr.trim()}`);
  return listed.stdout.split('\0').filter((file) => file && file !== ITSELF && !BINARY.test(file));
}

function privateRule() {
  const source = process.env.Q6_REPORT_PRIVATE_NAMES;
  if (!source) {
    const why =
      'Q6_REPORT_PRIVATE_NAMES is not set, so no project or team name was checked; it is a pattern of those names, kept as the repository secret of the same name';
    if (process.env.CI) throw new Error(why);
    console.log(`note: ${why}.`);
    return undefined;
  }
  return { name: 'a private name', pattern: new RegExp(source, 'i') };
}

const rules = [...RULES, privateRule()].filter(Boolean);
const found = [];
const files = filesOfTheRepository();
for (const file of files) {
  readFileSync(file, 'utf8')
    .split('\n')
    .forEach((line, index) => {
      for (const rule of rules) {
        const checked = rule.allowed ? line.replace(rule.allowed, '') : line;
        // The private names are never printed, so a failure on them in a public log names only the line.
        if (rule.pattern.test(checked))
          found.push(`${file}:${index + 1}: ${rule.name}${rule.name === 'a private name' ? '' : `: ${line.trim().slice(0, 120)}`}`);
      }
    });
}
if (found.length) {
  console.error(
    `${found.length} ${found.length === 1 ? 'line names' : 'lines name'} what this repository must not:\n${found.map((line) => `  ${line}`).join('\n')}`,
  );
  process.exit(1);
}
console.log(`ok: ${files.length} files name nothing but q6-report${rules.length > RULES.length ? ', with the private names checked' : ''}`);
